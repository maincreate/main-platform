/**
 * Deterministic GitHub Actions routing for a specific Main{Create}-managed builder.
 * Generates a READ-ONLY workflow file. Applying it to a repository requires an
 * intentional user commit. The separate label activation modifies only GitHub
 * runner labels, never the repository or connected hardware.
 */
import {releases,classifyBuilder} from "./marketplace_planning.mjs";

const bad=(message,status=422)=>Object.assign(new Error(message),{status});
const githubName=/^[A-Za-z0-9][A-Za-z0-9_.-]{0,59}$/;
const ghHeaders=token=>({
 "authorization":"Bearer "+token,"accept":"application/vnd.github+json",
 "x-github-api-version":"2022-11-28","user-agent":"Main{Create}"
});

export const labelForGithubRunnerId=id=>{
 if(!Number.isSafeInteger(id)||id<=0)throw bad("GitHub runner ID is invalid");
 return "maincreate-host-"+id;
};

function validState({route,project,builder,organization}){
 if(!route||!project||!builder||!organization)throw bad("Choose a saved, synchronized build route",409);
 if(route.organization!==organization||route.repository!==project.fullName||project.archived)
  throw bad("Routing must reference an active repository in the connected organization",409);
 if(!project.private)throw bad("Self-hosted builder workflows require a private repository or a separately isolated public-runner pool",403);
 if(!builder.managedHost||builder.decommission||route.buildBuilderId!==builder.id)
  throw bad("Selected builder must be the enrolled managed host",409);
 if(!githubName.test(builder.githubRunnerName||""))
  throw bad("Connect this builder to a GitHub Actions runner before generating the workflow",409);
 if(route.buildTrigger!=="github-actions")throw bad("Choose GitHub Actions as the project's trigger");
 if(route.sdk?.family!=="esp-idf"||route.sdk?.version!=="5.5.6")
  throw bad("ESP-IDF 5.5.6 is the only firmware workflow supported in this preview");
 if(builder.os!=="linux"||builder.arch!=="arm64")
  throw bad("This ESP-IDF preview workflow currently supports Linux ARM64 managed builders only",409);
 const release=releases().find(r=>r.family==="esp-idf"&&r.version==="5.5.6");
 if(!release||!classifyBuilder(builder,release).compatible)throw bad("The selected SDK is not compatible with the builder",409);
}
export function firmwareWorkflowPreview({route,project,builder,organization}){
 validState({route,project,builder,organization});
 const label=route.githubRunnerLabel;
 if(!/^maincreate-host-\d+$/.test(label||"")||!Number.isSafeInteger(route.githubRunnerId)||
  label!==labelForGithubRunnerId(route.githubRunnerId)||route.githubRunnerName!==builder.githubRunnerName)
  return {ready:false,reason:"Provision a unique GitHub runner label before generating a routable workflow",
   needsLabelProvisioning:true,workflow:null};
 const workflow=`# Generated by Main{Create}. Review before committing to your repository.
# Pinned builder label selects one specific organization-owned runner.
# This workflow NEVER flashes hardware. USB writes require a separate, approved adapter.
name: Main{Create} firmware build

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: maincreate-build-\${{ github.repository }}
  cancel-in-progress: false

jobs:
  firmware:
    if: github.event_name != 'pull_request'
    runs-on: [self-hosted, ${label}]
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@v7
        with:
          persist-credentials: false
          submodules: recursive
      - name: Verify ESP-IDF 5.5.6 and build
        shell: bash
        run: |
          set -euo pipefail
          : "\${IDF_PATH:?Set IDF_PATH in this runner's environment to the approved ESP-IDF 5.5.6 directory}"
          test -f "\${IDF_PATH}/export.sh"
          source "\${IDF_PATH}/export.sh"
          idf_version="$(idf.py --version)"
          case "$idf_version" in
            *"v5.5.6"*) ;;
            *) echo "Expected ESP-IDF v5.5.6, got $idf_version" >&2; exit 1 ;;
          esac
          idf.py build
          find build -type f \\( -name '*.bin' -o -name 'flasher_args.json' -o -name 'project_description.json' \\) -print0 |
            sort -z | xargs -0 -r sha256sum > build/maincreate-sha256.txt
          test -s build/maincreate-sha256.txt
      - name: Upload firmware artifact and integrity manifest
        uses: actions/upload-artifact@v6
        with:
          name: maincreate-firmware-\${{ github.sha }}
          path: |
            build/**/*.bin
            build/*.bin
            build/flasher_args.json
            build/project_description.json
            build/maincreate-sha256.txt
          if-no-files-found: error
`;
 return {ready:true,reason:null,needsLabelProvisioning:false,workflow,
  filePath:".github/workflows/maincreate-firmware.yml",runnerLabel:label,
  safety:"Build-only. No automatic flash, and project files must be reviewed before running on this trusted self-hosted builder."};
}

export async function provisionRunnerLabel({route,project,builder,organization,token,fetchImpl=fetch}){
 validState({route,project,builder,organization});
 if(typeof token!=="string"||token.length<20)throw bad("GitHub authorization is missing",409);
 const base="https://api.github.com/orgs/"+encodeURIComponent(organization)+"/actions/runners";
 let matching=null;
 for(let page=1;page<=5;page++){
  const url=base+"?per_page=100&page="+page;
  const response=await fetchImpl(url,{headers:ghHeaders(token),signal:AbortSignal.timeout(15000)});
  if(!response.ok)throw bad("Cannot list GitHub organization runners (HTTP "+response.status+")",502);
  const json=await response.json();
  if(!Array.isArray(json.runners))throw bad("Invalid GitHub runner response",502);
  const found=json.runners.filter(r=>r.name===builder.githubRunnerName);
  if(found.length>1)throw bad("Ambiguous GitHub runner name",409);
  if(found.length===1){matching=found[0];break;}
  if(json.runners.length<100)break;
 }
 if(!matching||!Number.isSafeInteger(matching.id))throw bad("Connected GitHub runner not found in organization",409);
 if(matching.status!=="online")throw bad("Selected GitHub runner is offline; do not provision an inactive host",409);
 const label=labelForGithubRunnerId(matching.id);
 // POST adds one custom label without erasing existing runner labels.
 const endpoint=base+"/"+matching.id+"/labels";
 const response=await fetchImpl(endpoint,{method:"POST",headers:{...ghHeaders(token),"content-type":"application/json"},
   body:JSON.stringify({labels:[label]}),signal:AbortSignal.timeout(15000)});
 if(!response.ok)throw bad("GitHub denied runner label provisioning (HTTP "+response.status+"). Check Self-hosted runners: write permission.",response.status===403?403:502);
 const body=await response.json().catch(()=>({}));
 const confirmed=Array.isArray(body.labels)&&body.labels.some(l=>l.name===label);
 if(!confirmed)throw bad("GitHub did not confirm the project routing label",502);
 return {runnerId:matching.id,runnerName:matching.name,label,at:new Date().toISOString()};
}
